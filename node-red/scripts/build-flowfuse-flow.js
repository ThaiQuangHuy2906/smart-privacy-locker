'use strict';

const fs = require('node:fs');
const path = require('node:path');

const nodeRedRoot = path.resolve(__dirname, '..');
const repositoryRoot = path.resolve(nodeRedRoot, '..');
const sourceFlowPath = path.join(nodeRedRoot, 'flows.json');
const outputFlowPath = path.join(nodeRedRoot, 'flows.flowfuse.json');
const runtimeEnvironmentKeys = Object.freeze([
  'SUPABASE_URL',
  'SUPABASE_ANON_KEY',
  'TELEGRAM_BOT_TOKEN',
  'TELEGRAM_CHAT_ID',
  'DASHBOARD_BASE_URL',
  'REPORT_TIMEZONE',
  'GEMINI_API_KEY',
  'GEMINI_MODEL',
  'DEVICE_STALE_AFTER_SECONDS',
  'COMMAND_TIMEOUT_MS',
  'AUTHORIZED_UNLOCK_WINDOW_SECONDS',
]);

function readText(target) {
  return fs.readFileSync(target, 'utf8').replace(/\r\n?/g, '\n');
}

function readJson(target) {
  return JSON.parse(readText(target));
}

function runtimeModuleSources() {
  return fs.readdirSync(path.join(nodeRedRoot, 'lib'))
    .filter((name) => name.endsWith('.js'))
    .sort()
    .map((name) => ({
      id: `./${path.basename(name, '.js')}`,
      source: readText(path.join(nodeRedRoot, 'lib', name)),
    }));
}

function moduleFactoriesSource(modules) {
  return modules.map(({ id, source }) => [
    `${JSON.stringify(id)}: function(module, exports, require) {`,
    source,
    '}',
  ].join('\n')).join(',\n');
}

function buildRuntimeBootstrap() {
  const factories = moduleFactoriesSource(runtimeModuleSources());
  return [
    "'use strict';",
    '',
    '// Generated by scripts/build-flowfuse-flow.js from the tested modules in lib/.',
    'const __splModules = {',
    factories,
    '};',
    'const __splModuleCache = Object.create(null);',
    '',
    'function __splLoad(request) {',
    "  if (request === 'node:crypto' || request === 'crypto') return crypto;",
    "  const id = String(request).replace(/\\.js$/, '');",
    '  if (__splModuleCache[id]) return __splModuleCache[id].exports;',
    '  const factory = __splModules[id];',
    "  if (!factory) throw new Error(`Unsupported bundled module: ${id}`);",
    '  const module = { exports: {} };',
    '  __splModuleCache[id] = module;',
    '  const localRequire = (dependency) => {',
    "    if (dependency === 'node:crypto' || dependency === 'crypto') return crypto;",
    "    if (String(dependency).startsWith('./')) return __splLoad(dependency);",
    "    throw new Error(`External module is not allowed by the Phase 2 bundle: ${dependency}`);",
    '  };',
    '  factory(module, module.exports, localRequire);',
    '  return module.exports;',
    '}',
    '',
    'class __SplAbortSignal {',
    '  constructor() { this.aborted = false; this.listeners = new Set(); }',
    "  addEventListener(type, listener) { if (type === 'abort' && typeof listener === 'function') this.listeners.add(listener); }",
    "  removeEventListener(type, listener) { if (type === 'abort') this.listeners.delete(listener); }",
    '  dispatchAbort() {',
    '    if (this.aborted) return;',
    '    this.aborted = true;',
    '    for (const listener of [...this.listeners]) listener();',
    '    this.listeners.clear();',
    '  }',
    '}',
    'class __SplAbortController {',
    '  constructor() { this.signal = new __SplAbortSignal(); }',
    '  abort() { this.signal.dispatchAbort(); }',
    '}',
    'const AbortController = __SplAbortController;',
    '',
    'function __splAbortError() {',
    "  const error = new Error('Request aborted');",
    "  error.name = 'AbortError';",
    '  return error;',
    '}',
    '',
    'function __splHttpsFetch(input, options = {}) {',
    '  return new Promise((resolve, reject) => {',
    '    let url;',
    '    try { url = new URL(input); } catch { reject(new Error(\'Invalid HTTPS URL\')); return; }',
    "    if (url.protocol !== 'https:') { reject(new Error('Only HTTPS provider URLs are allowed')); return; }",
    '',
    '    const signal = options.signal;',
    '    if (signal?.aborted) { reject(__splAbortError()); return; }',
    '    let settled = false;',
    '    let request;',
    '    const cleanup = () => signal?.removeEventListener?.(\'abort\', onAbort);',
    '    const fail = (error) => {',
    '      if (settled) return;',
    '      settled = true;',
    '      cleanup();',
    '      reject(error);',
    '    };',
    '    const onAbort = () => request?.destroy(__splAbortError());',
    '',
    '    request = https.request(url, {',
    "      method: String(options.method || 'GET').toUpperCase(),",
    '      headers: options.headers || {},',
    '      rejectUnauthorized: true,',
    '    }, (response) => {',
    '      const chunks = [];',
    '      let size = 0;',
    '      response.on(\'data\', (chunk) => {',
    '        const value = Buffer.isBuffer(chunk) ? chunk : Buffer.from(chunk);',
    '        size += value.length;',
    '        if (size > 1024 * 1024) {',
    "          response.destroy(new Error('Provider response exceeds 1 MiB'));",
    '          return;',
    '        }',
    '        chunks.push(value);',
    '      });',
    '      response.on(\'error\', fail);',
    '      response.on(\'end\', () => {',
    '        if (settled) return;',
    '        settled = true;',
    '        cleanup();',
    "        const body = Buffer.concat(chunks).toString('utf8');",
    '        const status = Number(response.statusCode || 0);',
    '        resolve({',
    '          ok: status >= 200 && status < 300,',
    '          status,',
    '          headers: response.headers,',
    '          async text() { return body; },',
    '          async json() { return JSON.parse(body); },',
    '        });',
    '      });',
    '    });',
    '    request.on(\'error\', fail);',
    '    signal?.addEventListener?.(\'abort\', onAbort, { once: true });',
    '    if (options.body !== undefined && options.body !== null) request.write(options.body);',
    '    request.end();',
    '  });',
    '}',
    '',
    `const __splEnvironmentKeys = ${JSON.stringify(runtimeEnvironmentKeys)};`,
    'const __splEnvironment = Object.fromEntries(',
    '  __splEnvironmentKeys.map((key) => [key, env.get(key)]),',
    ');',
    "const __splCreateFromEnvironment = __splLoad('./runtime').createFromEnvironment;",
    'const __splFactory = (options = {}) => __splCreateFromEnvironment({',
    '  env: __splEnvironment,',
    '  fetchImpl: __splHttpsFetch,',
    '  uuid: () => crypto.randomUUID(),',
    '  ...options,',
    '});',
    'const __splOutbox = [];',
    'const __splRuntime = __splFactory({',
    '  publish: (topic, payload, options) => __splOutbox.push({ topic, payload, options }),',
    '});',
    "global.set('splRuntimeFactory', __splFactory);",
    "global.set('splOutbox', __splOutbox);",
    "global.set('splRuntime', __splRuntime);",
    '',
    "const __splMissing = ['SUPABASE_URL', 'SUPABASE_ANON_KEY']",
    '  .filter((key) => !__splEnvironment[key]);',
    'if (__splMissing.length) {',
    "  node.warn(`Phase 2 runtime is missing deployment variables: ${__splMissing.join(', ')}`);",
    '}',
    "if (Boolean(__splEnvironment.GEMINI_API_KEY) !== Boolean(__splEnvironment.GEMINI_MODEL)) {",
    "  node.warn('Set both GEMINI_API_KEY and GEMINI_MODEL, or leave both empty.');",
    '}',
    "node.status({ fill: 'green', shape: 'dot', text: 'FlowFuse runtime ready' });",
  ].join('\n');
}

function buildInlineDashboard() {
  let html = readText(path.join(repositoryRoot, 'dashboard', 'index.html'));
  const css = readText(path.join(repositoryRoot, 'dashboard', 'styles.css'))
    .replace(/<\/style/gi, '<\\/style');
  const javascript = readText(path.join(repositoryRoot, 'dashboard', 'app.js'))
    .replace(/<\/script/gi, '<\\/script');
  const stylesheetTag = '<link rel="stylesheet" href="styles.css">';
  const scriptTag = '<script src="app.js" defer></script>';
  if (!html.includes(stylesheetTag) || !html.includes(scriptTag)) {
    throw new Error('Dashboard entrypoint no longer contains the expected stylesheet/script tags');
  }
  html = html.replace(stylesheetTag, `<style>\n${css}\n  </style>`);
  html = html.replace(scriptTag, `<script>\n${javascript}\n  </script>`);
  return html;
}

function runtimeUnavailableResponse(outputs = 1) {
  const response = [
    "if (!runtime) {",
    "  msg.statusCode = 503;",
    "  msg.payload = { ok: false, status: 503, code: 'RUNTIME_STARTING' };",
  ];
  response.push(outputs === 1 ? '  return msg;' : '  return [msg, null];');
  response.push('}');
  return response.join('\n');
}

function protectRuntimeConsumers(flows) {
  const protectedFunctions = [
    { id: 'cmd_fn', outputs: 2 },
    { id: 'chat_fn', outputs: 1 },
    { id: 'claim_fn', outputs: 1 },
    { id: 'state_fn', outputs: 1 },
  ];
  for (const { id, outputs } of protectedFunctions) {
    const node = flows.find((candidate) => candidate.id === id);
    if (!node) throw new Error(`Missing protected Function node: ${id}`);
    const declaration = "const runtime=global.get('splRuntime');";
    if (!node.func.includes(declaration)) throw new Error(`Unexpected runtime declaration in ${id}`);
    node.func = node.func.replace(declaration, `${declaration}\n${runtimeUnavailableResponse(outputs)}`);
  }
}

function addFlowFuseDashboardRoute(flows) {
  const inlineDashboard = buildInlineDashboard();
  const uiTemplate = flows.find((node) => node.id === 'ui_template');
  if (!uiTemplate) throw new Error('Missing ui_template node');
  uiTemplate.format = '<template><iframe title="Smart Privacy Locker Phase 2" src="/phase2" style="width:100%;height:80vh;border:0;border-radius:12px"></iframe></template>';

  flows.push(
    {
      id: 'phase2_static_http', type: 'http in', z: 'tab_dashboard',
      name: 'GET self-contained Phase 2 app', url: '/phase2', method: 'get',
      upload: false, swaggerDoc: '', x: 200, y: 380, wires: [['phase2_static_fn']],
    },
    {
      id: 'phase2_static_fn', type: 'function', z: 'tab_dashboard',
      name: 'Serve embedded Dashboard assets',
      func: `msg.payload=${JSON.stringify(inlineDashboard)};return msg;`,
      outputs: 1, noerr: 0, initialize: '', finalize: '', libs: [],
      x: 510, y: 380, wires: [['phase2_static_response']],
    },
    {
      id: 'phase2_static_response', type: 'http response', z: 'tab_dashboard',
      name: 'Phase 2 app response', statusCode: '200',
      headers: {
        'content-type': 'text/html; charset=utf-8',
        'cache-control': 'no-store',
        'x-content-type-options': 'nosniff',
        'referrer-policy': 'no-referrer',
        'x-frame-options': 'SAMEORIGIN',
      },
      x: 820, y: 380, wires: [],
    },
  );
}

function configureMqttTls(flows) {
  const brokerIndex = flows.findIndex((node) => node.id === 'broker');
  if (brokerIndex < 0) throw new Error('Missing MQTT broker configuration node');
  const broker = flows[brokerIndex];
  broker.name = 'Authenticated MQTT over verified TLS';
  broker.clientid = '';
  broker.usetls = true;
  broker.tls = 'broker_tls';
  flows.splice(brokerIndex + 1, 0, {
    id: 'broker_tls', type: 'tls-config', name: 'Verify MQTT broker certificate',
    cert: '', key: '', ca: '', certname: '', keyname: '', caname: '',
    servername: '', verifyservercert: true, alpnprotocol: '',
  });
}

function buildFlowFuseFlow() {
  const flows = readJson(sourceFlowPath);
  const initializer = flows.find((node) => node.id === 'init_fn');
  if (!initializer) throw new Error('Missing init_fn Function node');
  initializer.name = 'Bootstrap self-contained FlowFuse runtime';
  initializer.initialize = buildRuntimeBootstrap();
  initializer.libs = [
    { var: 'crypto', module: 'crypto' },
    { var: 'https', module: 'https' },
  ];

  let settingsReferences = 0;
  for (const node of flows.filter((candidate) => candidate.type === 'function')) {
    const rewritten = node.func.replaceAll(
      "node.error('splRuntimeFactory missing; apply settings.example.js')",
      "node.error('FlowFuse runtime bootstrap unavailable')",
    );
    if (rewritten !== node.func) settingsReferences += 1;
    node.func = rewritten;
  }
  if (settingsReferences === 0) throw new Error('Expected at least one self-hosted settings reference to replace');

  protectRuntimeConsumers(flows);
  configureMqttTls(flows);
  addFlowFuseDashboardRoute(flows);
  flows.push({
    id: 'flowfuse_export_note', type: 'comment', z: 'tab_mqtt',
    name: 'Generated FlowFuse Cloud export',
    info: 'Regenerate with npm run build:flowfuse. Runtime and Dashboard assets are embedded. MQTT credentials remain in the Node-RED credential store.',
    x: 470, y: 360, wires: [],
  });
  return flows;
}

function serializeFlowFuseFlow() {
  return `${JSON.stringify(buildFlowFuseFlow(), null, 2)}\n`;
}

function writeFlowFuseFlow() {
  fs.writeFileSync(outputFlowPath, serializeFlowFuseFlow(), 'utf8');
  process.stdout.write(`Generated ${path.relative(repositoryRoot, outputFlowPath)}\n`);
}

if (require.main === module) writeFlowFuseFlow();

module.exports = {
  buildFlowFuseFlow,
  buildInlineDashboard,
  buildRuntimeBootstrap,
  runtimeEnvironmentKeys,
  serializeFlowFuseFlow,
};
